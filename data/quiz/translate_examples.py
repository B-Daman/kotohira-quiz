def main():
    input_path = "C:/Users/user/hisho-bot/data/quiz/english_questions.json"

    with open(input_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated = 0
    missing = []

    for q in data["questions"]:
        exp = q["explanation"]
        # Extract the example sentence
        match = re.search(r"例[:：]\s*(.+)$", exp)
        if not match:
            missing.append(f"{q['id']}: no example found")
            continue

        example = match.group(1).strip()

        if example in TRANSLATIONS:
            ja = TRANSLATIONS[example]
            # Add Japanese translation in parentheses after the English example
            new_exp = exp + "（" + ja + "）"
            q["explanation"] = new_exp
            updated += 1
        else:
            missing.append(f"{q['id']}: {example}")

    print(f"Updated: {updated}/{len(data['questions'])}")
    if missing:
        print(f"Missing translations ({len(missing)}):")
        for m in missing:
            print(f"  {m}")

    if updated == len(data["questions"]):
        with open(input_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print("File written successfully!")
    else:
        print("NOT writing file due to missing translations.")


if __name__ == "__main__":
    main()
